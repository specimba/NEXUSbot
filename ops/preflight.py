#!/usr/bin/env python3
"""NEXUS OS — secret presence preflight.

Reads ops/secrets.required.yaml (names/scopes only), checks the environment,
and prints MASKED status. It never prints, writes, or logs a full value.

Usage:
  python3 ops/preflight.py                  presence check (offline)
  python3 ops/preflight.py --emit-example   regenerate .env.example from the manifest
  python3 ops/preflight.py --validate       also run each entry's validate command (network)
  python3 ops/preflight.py --json           machine-readable summary
  python3 ops/preflight.py --quiet          only failures

Exit: 0 = all required present, 1 = missing required, 2 = manifest error.
"""

from __future__ import annotations

import json
import os
import shlex
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = Path(__file__).resolve().parent / "secrets.required.yaml"
EXAMPLE = ROOT / ".env.example"

TOP_KEYS = {"version", "project", "policy", "mask", "storage_local",
            "storage_portable", "example_file", "owner"}


def parse_manifest(path: Path) -> tuple[dict, list[dict], list[str]]:
    """Parse the strict subset of YAML used by the manifest (flat maps only)."""
    meta: dict[str, str] = {}
    entries: list[dict] = []
    never: list[str] = []
    mode = None
    cur: dict | None = None

    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.rstrip()
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        indent = len(line) - len(line.lstrip())

        if indent == 0:
            key, _, val = line.partition(":")
            key = key.strip()
            if key == "entries":
                mode, cur = "entries", None
                continue
            if key == "never_store":
                mode, cur = "never", None
                continue
            meta[key] = val.strip().strip('"').strip("'")
            continue

        if mode == "entries":
            if line.lstrip().startswith("- "):
                cur = {}
                entries.append(cur)
                body = line.lstrip()[2:]
                if ":" in body:
                    k, _, v = body.partition(":")
                    cur[k.strip()] = v.strip().strip('"').strip("'")
            elif cur is not None and ":" in line:
                k, _, v = line.strip().partition(":")
                cur[k.strip()] = v.strip().strip('"').strip("'")
        elif mode == "never":
            item = line.lstrip()
            if item.startswith("- "):
                never.append(item[2:].strip())

    if not entries:
        raise ValueError("no entries found in manifest")
    for e in entries:
        if "name" not in e:
            raise ValueError(f"entry without name: {e}")
    return meta, entries, never


def mask(value: str, style: str = "last4") -> str:
    n = len(value)
    if n == 0:
        return "empty"
    if style == "last4" and n >= 12:
        return f"…{value[-4:]} ({n} chars)"
    if style == "last4" and n >= 4:
        return f"…{value[-2:]} ({n} chars)"
    return f"set ({n} chars)"


def example_value(entry: dict) -> str:
    kind = entry.get("kind", "")
    name = entry.get("name", "")
    if kind == "dsn":
        if name.startswith("REDIS"):
            return "redis://localhost:6379/0"
        return "postgresql://nexus:CHANGE_ME@localhost:5432/nexus"
    if kind == "url":
        return "http://localhost:8787"
    return ""


def emit_example(entries: list[dict], path: Path, source: Path) -> None:
    out = [
        f"# GENERATED by {source.name} — do not edit by hand.",
        f"# Source of truth: {source.relative_to(ROOT)}",
        "# Fill values locally. This file is safe to commit; .env is not.",
        "",
    ]
    for e in entries:
        req = "required" if e.get("required", "true") == "true" else "optional"
        out.append(f"# {e['name']} — {req}: {e.get('purpose','')}")
        if e.get("scope"):
            out.append(f"# scope: {e['scope']}")
        out.append(f"{e['name']}={example_value(e)}")
        out.append("")
    path.write_text("\n".join(out), encoding="utf-8")


def gitignore_ok() -> bool:
    gi = ROOT / ".gitignore"
    if not gi.exists():
        return False
    lines = {ln.strip() for ln in gi.read_text(encoding="utf-8").splitlines()}
    return bool({".env", "/.env", ".env*"} & lines)


def run_validate(cmd: str) -> tuple[bool, str]:
    if cmd.strip() in ("", "true"):
        return True, "skipped"
    try:
        r = subprocess.run(shlex.split(cmd), capture_output=True, text=True, timeout=15)
    except (FileNotFoundError, subprocess.TimeoutExpired) as exc:
        return False, type(exc).__name__
    if r.returncode == 0:
        return True, "ok"
    first = (r.stderr or r.stdout or "").strip().splitlines()
    tail = first[-1][:80] if first else "failed"
    return False, tail


def main(argv: list[str]) -> int:
    if not MANIFEST.exists():
        print(f"FATAL: manifest not found: {MANIFEST}", file=sys.stderr)
        return 2
    meta, entries, never = parse_manifest(MANIFEST)
    emit = "--emit-example" in argv

    if emit:
        emit_example(entries, EXAMPLE, MANIFEST)
        print(f"wrote {EXAMPLE.relative_to(ROOT)} ({len(entries)} entries)")
        if not gitignore_ok():
            print("WARN: .gitignore does not ignore .env — fix before the first commit")

    style = meta.get("mask", "last4")
    rows, missing, optional_missing = [], [], []
    for e in entries:
        name = e["name"]
        val = os.environ.get(name, "")
        required = e.get("required", "true") == "true"
        if val:
            status, detail = "SET", mask(val, style)
            if "--validate" in argv:
                ok, note = run_validate(e.get("validate", "true"))
                status, detail = ("SET ok" if ok else "SET FAIL"), (detail if ok else note)
        else:
            status, detail = ("MISSING" if required else "unset (optional)"), "—"
            (missing if required else optional_missing).append(name)
        rows.append({"name": name, "required": required, "status": status, "detail": detail})

    if "--json" in argv:
        print(json.dumps({"project": meta.get("project"), "rows": rows,
                          "missing": missing, "optional_missing": optional_missing}, indent=2))
    elif "--quiet" not in argv or missing:
        width = max(len(r["name"]) for r in rows)
        print(f"{meta.get('project','project')} — {len(rows)} entries, "
              f"{len(entries)-len(missing)-len(optional_missing)} set, "
              f"{len(missing)} missing required")
        print("-" * (width + 40))
        for r in rows:
            print(f"{r['name']:<{width}}  {r['status']:<17} {r['detail']}")
        if never:
            print(f"\nNever stored here: {', '.join(never)}")

    if missing:
        sys.stdout.flush()
        print(f"\nMissing required: {', '.join(missing)}", file=sys.stderr)
        print("Enter them in .env locally (see .env.example). Do not paste them into chat.",
              file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
